import {test,expect} from '@playwright/test';
import {openTool} from './spatial-helpers.ts';
test('Mira avatar responds to selection, speech preview and motion preferences',async({page})=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
  await page.emulateMedia({reducedMotion:'no-preference'});await page.goto('./');
  const avatar=page.locator('.avatar-face'),surface=page.locator('.voice-output'),hud=avatar.locator('.avatar-hud');
  await expect(avatar).toBeVisible();
  await expect(avatar.locator('.face')).toHaveAttribute('src',/mira-avatar/);
  await expect(avatar.locator('.avatar-lid')).toHaveCount(2);
  await expect(avatar.locator('.avatar-glint')).toHaveCount(2);
  await expect(avatar.locator('.avatar-mouth-trace')).toHaveCount(1);
  await expect(hud).toBeVisible();
  await expect(avatar).toHaveCSS('--avatar-cyan','#28d9f5');
  const idleFrame=await hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL());
  await expect.poll(()=>hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL())).not.toBe(idleFrame);
  await page.mouse.move(1300,740);
  await expect.poll(()=>avatar.locator('.avatar-glint-left').evaluate(el=>getComputedStyle(el).getPropertyValue('--gaze-x'))).not.toBe('0%');
  await page.screenshot({path:'artifacts/mira-idle-desktop.png'});
  await openTool(page,'Weather');await expect(avatar).toHaveAttribute('data-focused','true');
  await page.getByRole('button',{name:'Close panel',exact:true}).click();
  await expect(avatar).toHaveAttribute('data-focused','false');
  await page.getByRole('button',{name:'Preview waves',exact:true}).click();
  await expect(surface).toHaveAttribute('data-visual-state','speaking');
  await expect(page.getByRole('button',{name:'Stop preview',exact:true})).toHaveCSS('background-color','rgba(0, 0, 0, 0)');
  await expect(avatar).toHaveCSS('--avatar-cyan','#87f4ff');
  await expect.poll(async()=>Number(await surface.evaluate(el=>getComputedStyle(el).getPropertyValue('--core-energy')))).toBeGreaterThan(.2);
  await expect.poll(()=>avatar.locator('.avatar-mouth-trace').evaluate(el=>Number.parseFloat(getComputedStyle(el).opacity))).toBeGreaterThan(.3);
  await page.screenshot({path:'artifacts/mira-speaking.png'});
  await page.getByRole('button',{name:'Stop preview',exact:true}).click();
  await expect(surface).toHaveAttribute('data-visual-state','idle');
  await expect(surface).toHaveCSS('--core-energy','0');
  await page.emulateMedia({reducedMotion:'reduce'});
  const still=await hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL());await page.waitForTimeout(180);
  expect(await hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL())).toBe(still);
  await page.getByRole('button',{name:'Preview waves',exact:true}).click();
  await expect(surface).toHaveCSS('--core-energy','0');
  await page.getByRole('button',{name:'Stop preview',exact:true}).click();
  await page.emulateMedia({reducedMotion:'no-preference'});
  await page.evaluate(()=>{Object.defineProperty(document,'hidden',{configurable:true,value:true});document.dispatchEvent(new Event('visibilitychange'));});
  const frozen=await hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL());await page.waitForTimeout(180);
  expect(await hud.evaluate(el=>(el as HTMLCanvasElement).toDataURL())).toBe(frozen);
  expect(errors).toEqual([]);
});

test('mobile avatar and touch tools retain their space and selection behavior',async({browser})=>{
  const context=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,reducedMotion:'no-preference'});
  const page=await context.newPage();await page.goto('http://127.0.0.1:3099/jarvis/');
  await page.screenshot({path:'artifacts/mira-mobile.png'});
  const avatar=page.locator('.avatar-face'),box=await avatar.boundingBox();expect(box!.width).toBeGreaterThan(200);expect(box!.x).toBeGreaterThan(0);
  await page.getByRole('navigation',{name:'Floating tools'}).getByRole('button',{name:'Music',exact:true}).tap();
  await expect(avatar).toHaveAttribute('data-focused','true');
  await expect(page.locator('.voice-output')).toHaveAttribute('data-visual-state','idle');
  await expect(page.getByRole('button',{name:'Close panel',exact:true})).toBeVisible();
  await context.close();
});
